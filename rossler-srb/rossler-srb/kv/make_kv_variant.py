"""Generate a Kv verification program for a tangency near c = 5.7 from the template
tangency_kv.cpp (the program for the band-merging tangency), substituting ONLY numerical parameters and the
statement being checked (exact endpoints of J, decimal boxes, bounds); the checks are the same.

usage: python3 make_kv_variant.py <name> <json-file-with-parameters>   (the json files of the CAPD
variants, params_*.json, are used: they contain the keys cL_exact, cR_exact, QK, Q, lamu, det)
"""
import os, sys, json
here = os.path.dirname(os.path.abspath(__file__))
tpl = os.path.join(here, "tangency_kv.cpp")                      # layout of the release archive
if not os.path.exists(tpl):
    tpl = os.path.join(here, "..", "indep_kv", "tangency_kv.cpp")  # layout of the working tree
src = open(tpl).read()
name, pfile = sys.argv[1], sys.argv[2]
P = json.load(open(pfile))
def sub(old, new):
    global src
    if src.count(old) != 1: raise SystemExit("pattern count %d: %s" % (src.count(old), old))
    src = src.replace(old, new)
sub("static const double E_[2][2] = {{0.9999996961880596, -0.8077389541129416},\n                                {7.795022697815469e-4, -0.5895403141503822}};",
    "static const double E_[2][2] = {{%s, %s},\n                                {%s, %s}};" % (P["E00"], P["E01"], P["E10"], P["E11"]))
sub("static double PH[2] = {-6.938698731191516, 0.03606348866252088};", "static double PH[2] = {%s, %s};" % (P["py"], P["pz"]))
sub("static const double DPH[2] = {-1.2318423388002486, -0.00664781927076086};", "static const double DPH[2] = {%s, %s};" % (P["dpy"], P["dpz"]))
sub("const double cmid = 4.50698934631197 + cshift;", "const double cmid = %s + cshift;" % P["cmid"])
sub("const double epsc = 1e-8;", "const double epsc = %s;" % P.get("epsc", "1e-8"))
sub("const int N = 15;", "const int N = %d;" % (P["K2"] + P["n"]))
sub("const double sm = 5.3682155586e-4;", "const double sm = %s;" % P["smid"])
sub("const double Delta = (argc > 1) ? atof(argv[1]) : 1e-9;", "const double Delta = (argc > 1) ? atof(argv[1]) : %s;" % P.get("Delta", "1e-9"))
sub("const double delta_u = 6e-4, rho = 1e-5;", "const double delta_u = %s, rho = 1e-5;" % P["delta_u"])
# statement of the theorem as printed in the paper
sub('const char* QK_dec[4] = {"-6.9386987611", "-6.9386987012", "0.0360634877", "0.0360634896"};',
    'const char* QK_dec[4] = {"%s", "%s", "%s", "%s"};' % tuple(P["QK"]))
sub('const char* Q_dec[4]  = {"-6.9386987439", "-6.9386987185", "0.0360634882", "0.0360634892"};',
    'const char* Q_dec[4]  = {"%s", "%s", "%s", "%s"};' % tuple(P["Q"]))
sub('const char* LAMU_dec[2] = {"-1.92148", "-1.92146"};', 'const char* LAMU_dec[2] = {"%s", "%s"};' % tuple(P["lamu"]))
sub('const char* DET_dec = "0.00000005";', 'const char* DET_dec = "%s";' % P["det"])
sub("""cL == 4.50698933631197018456759906257502734661102294921875 &&
			      cR == 4.50698935631197006301817964413203299045562744140625""",
    """cL == %s &&
			      cR == %s""" % (P["cL_exact"], P["cR_exact"]))
sub("// Independent computer-assisted verification (Kv library), for the paper \"Existence of SRB measures",
    "// [variant '%s' generated by make_kv_variant.py from tangency_kv.cpp: tangency near c = %s;\n"
    "//  only numerical parameters and the statement being checked differ]\n"
    "// Independent computer-assisted verification (Kv library), for the paper \"Existence of SRB measures" % (name, P["cmid"]))
open(name + ".cpp", "w").write(src)
print("wrote", name + ".cpp")
