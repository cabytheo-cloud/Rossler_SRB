"""Create a CAP program for a tangency near c = 5.7 by copying tangency_cap.cpp and
substituting ONLY the numerical parameters (the logic of the checks is left untouched).

usage: python3 make_variant.py <name> <json-file-with-parameters>
The json keys: cmid, K2, n, smid, delta_u, py, pz, dpy, dpz, E00, E01, E10, E11,
               QK, Q, lamu, det, dist (numerical statement as printed in the paper),
               (optional) epsc, Delta, rho, rs, ru, kry, krz, krp
               (cL_exact, cR_exact are used by the Kv generator only)
"""
import os, sys, json, re
here = os.path.dirname(os.path.abspath(__file__))
tpl = os.path.join(here, "tangency_cap.cpp")            # layout of the release archive
if not os.path.exists(tpl):
    tpl = os.path.join(here, "..", "cap", "tangency_cap.cpp")   # layout of the working tree
src = open(tpl).read()
name, pfile = sys.argv[1], sys.argv[2]
P = json.load(open(pfile))
d = lambda k, default=None: P.get(k, default)

def sub(old, new, count=1):
    global src
    if src.count(old) != count:
        raise SystemExit("pattern count mismatch (%d) for: %s" % (src.count(old), old))
    src = src.replace(old, new)

sub("    const double cmid  = 4.50698934631197 + cshift;   // numerical tangency parameter",
    "    const double cmid  = %s + cshift;   // numerical tangency parameter" % P["cmid"])
sub("    const double epsc  = (argc > 1) ? atof(argv[1]) : 1e-8;",
    "    const double epsc  = (argc > 1) ? atof(argv[1]) : %s;" % d("epsc", "1e-8"))
sub("    const int    K2    = 12;                    // iterates from W^u_loc to the fold",
    "    const int    K2    = %d;                    // iterates from W^u_loc to the fold" % P["K2"])
sub("    const int    N     = K2 + 3;                // iterates from W^u_loc to the tip near p",
    "    const int    N     = K2 + %d;                // iterates from W^u_loc to the tip near p" % P["n"])
sub("    const double smid  = 5.3682155586e-04;      // numerical critical parameter on W^u_loc",
    "    const double smid  = %s;      // numerical critical parameter on W^u_loc" % P["smid"])
sub("    const double Delta = (argc > 2) ? atof(argv[2]) : 1e-9;",
    "    const double Delta = (argc > 2) ? atof(argv[2]) : %s;" % d("Delta", "1e-9"))
sub("    const double delta_u = 6e-4;                // W^u_loc domain |u| <= delta_u",
    "    const double delta_u = %s;                // W^u_loc domain |u| <= delta_u" % P["delta_u"])
sub("    const double rs = 1e-6, ru = 1e-6;          // W^s_loc box |u|<=ru, |v|<=rs",
    "    const double rs = %s, ru = %s;          // W^s_loc box |u|<=ru, |v|<=rs" % (d("rs", "1e-6"), d("ru", "1e-6")))
sub("    IVector qt(2); qt[0] = -6.938698731191516 - 1.2318423388002486 * cshift; qt[1] = 0.03606348866252088 - 0.00664781927076086 * cshift;",
    "    IVector qt(2); qt[0] = %s + (%s) * cshift; qt[1] = %s + (%s) * cshift;" % (P["py"], P["dpy"], P["pz"], P["dpz"]))
sub("    E[0][0] = 9.999996961880596e-01;  E[0][1] = -8.077389541129416e-01;",
    "    E[0][0] = %s;  E[0][1] = %s;" % (P["E00"], P["E01"]))
sub("    E[1][0] = 7.795022697815469e-04;  E[1][1] = -5.895403141503822e-01;",
    "    E[1][0] = %s;  E[1][1] = %s;" % (P["E10"], P["E11"]))
sub("    const double dpy = -1.2318423388002486, dpz = -0.00664781927076086;",
    "    const double dpy = %s, dpz = %s;" % (P["dpy"], P["dpz"]))
if "kry" in P:
    sub('krawczyk(J, 3e-8, 1e-9, KJ)', 'krawczyk(J, %s, %s, KJ)' % (P["kry"], P["krz"]))
if "krp" in P:
    for w in ["cL), 1e-11, 1e-11, KL)", "cR), 1e-11, 1e-11, KR)", "cmid), 1e-11, 1e-11, KM)"]:
        sub(w, w.replace("1e-11, 1e-11", "%s, %s" % (P["krp"], P["krp"])))
if "rho" in P:
    sub("    double rho = 1e-5;  // a priori v-range of the box, verified below",
        "    double rho = %s;  // a priori v-range of the box, verified below" % P["rho"])
# numerical statement as printed in the paper (Table 2)
sub('    const char* QK_dec[4] = {"-6.9386987611", "-6.9386987012", "0.0360634877", "0.0360634896"};',
    '    const char* QK_dec[4] = {"%s", "%s", "%s", "%s"};' % tuple(P["QK"]))
sub('    const char* Q_dec[4]  = {"-6.9386987439", "-6.9386987185", "0.0360634882", "0.0360634892"};',
    '    const char* Q_dec[4]  = {"%s", "%s", "%s", "%s"};' % tuple(P["Q"]))
sub('    const char* LAMU_dec[2] = {"-1.92148", "-1.92146"};', '    const char* LAMU_dec[2] = {"%s", "%s"};' % tuple(P["lamu"]))
sub('    const char* DET_dec   = "0.00000005";', '    const char* DET_dec   = "%s";' % P["det"])
sub('    const char* DIST_dec  = "0.00000002";', '    const char* DIST_dec  = "%s";' % P["dist"])
# header comment: record provenance
sub("// on the section {x = 0, x' > 0}, as c varies in a small interval J.\n",
    "// on the section {x = 0, x' > 0}, as c varies in a small interval J.\n"
    "// [near57 variant '%s': generated by make_variant.py from tangency_cap.cpp;\n"
    "//  only numerical parameters differ (tangency near c = 5.7, n = %d, N = K2 + n = %d).]\n" % (name, P["n"], P["K2"] + P["n"]))
open(name + ".cpp", "w").write(src)
print("wrote", name + ".cpp")
